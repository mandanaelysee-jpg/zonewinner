-- ZoneWinner: table de pronostics publiée côté membre
-- À exécuter dans Supabase > SQL Editor du projet cuwoxrsovdbknjtwvzex.
create table if not exists public.pronostics (
  id bigint generated by default as identity primary key,
  title text,
  match_name text not null,
  competition text not null default 'Football',
  prediction text not null,
  odds numeric(8,2),
  status text not null default 'pending' check (status in ('pending','won','lost','void')),
  result text,
  kickoff_at timestamptz,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.pronostics enable row level security;

-- Les visiteurs authentifiés peuvent uniquement lire les lignes publiées.
drop policy if exists "Authenticated members read published pronostics" on public.pronostics;
create policy "Authenticated members read published pronostics"
on public.pronostics for select to authenticated
using (published = true);

-- Aucun accès anonyme et aucune écriture client : publication/édition via le tableau de bord Supabase
-- ou une future interface admin protégée côté serveur.
revoke all on public.pronostics from anon;
grant select on public.pronostics to authenticated;

